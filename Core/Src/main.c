uint32_t Get_us_Tickval(void)
{
    uint16_t high1, high2, low;

    do {
        high1 = htim3.Instance->CNT;
        low   = htim2.Instance->CNT;
        high2 = htim3.Instance->CNT;
    } while (high1 != high2);

    return ((uint32_t)high1 << 16) | low;
}


